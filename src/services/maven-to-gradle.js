class MavenToGradleError extends Error {
  constructor(message, { cause, stdout, stderr } = {}) {
    super(message, cause ? { cause } : undefined);
    this.name = 'MavenToGradleError';
    this.stdout = stdout;
    this.stderr = stderr;
  }
}

function parsePom(xml) {
  let document;

  try {
    document = new XMLParser({
      ignoreAttributes: false,
      attributeNamePrefix: '@_',
      trimValues: true,
      parseTagValue: false
    }).parse(xml);
  } catch (cause) {
    throw new MavenToGradleError('No se pudo analizar pom.xml.', { cause });
  }

  const project = document.project;
  if (!project || typeof project !== 'object') {
    throw new MavenToGradleError('pom.xml no contiene un elemento <project> vรกlido.');
  }

  const parent = asObject(project.parent);
  const rawProperties = asObject(project.properties);
  const properties = Object.fromEntries(
    Object.entries(rawProperties).map(([key, value]) => [key, scalar(value)])
  );
  const resolve = (value) => resolveProperty(value, properties);

  const groupId = resolve(scalar(project.groupId) || scalar(parent.groupId) || 'com.carrefour');
  const artifactId = resolve(scalar(project.artifactId));
  if (!artifactId) {
    throw new MavenToGradleError('pom.xml debe declarar <artifactId>.');
  }

  const dependencies = asArray(project.dependencies?.dependency)
    .map((dependency) => parseDependency(dependency, resolve))
    .filter((dependency) => dependency.artifactId);

  const managedDependencies = asArray(
    project.dependencyManagement?.dependencies?.dependency
  )
    .map((dependency) => parseDependency(dependency, resolve))
    .filter((dependency) => dependency.artifactId);

  const repositories = asArray(project.repositories?.repository)
    .map((repository) => ({
      id: resolve(scalar(repository.id)),
      url: resolve(scalar(repository.url))
    }))
    .filter((repository) => repository.url);

  const plugins = asArray(project.build?.plugins?.plugin)
    .map((plugin) => ({
      groupId: resolve(scalar(plugin.groupId) || 'org.apache.maven.plugins'),
      artifactId: resolve(scalar(plugin.artifactId)),
      version: resolve(scalar(plugin.version))
    }))
    .filter((plugin) => plugin.artifactId);

  const hasPlugin = (artifactId) =>
    plugins.some((plugin) => plugin.artifactId === artifactId);
  const hasSpringBoot = hasPlugin('spring-boot-maven-plugin') ||
    dependencies.some((dependency) =>
      dependency.groupId === 'org.springframework.boot'
    );
  const javaVersion = resolve(
    properties['java.version'] ||
      properties['maven.compiler.release'] ||
      properties['maven.compiler.source'] ||
      '17'
  );
  const googleRepository = repositories.find((repository) =>
    repository.url.startsWith('artifactregistry://') ||
    repository.url.includes('pkg.dev')
  )?.url;

  return {
    coordinates: {
      groupId,
      artifactId,
      version: resolve(scalar(project.version) || scalar(parent.version) || '0.0.1-SNAPSHOT'),
      name: resolve(scalar(project.name) || artifactId),
      description: resolve(scalar(project.description) || '')
    },
    properties: {
      ...properties,
      javaVersion,
      encoding: resolve(
        properties['project.build.sourceEncoding'] ||
          properties['project.reporting.outputEncoding'] ||
          'UTF-8'
      )
    },
    dependencies,
    managedDependencies,
    repositories,
    plugins,
    features: {
      springBoot: hasSpringBoot,
      jacoco: hasPlugin('jacoco-maven-plugin'),
      failsafe: hasPlugin('maven-failsafe-plugin'),
      sonar: hasPlugin('sonar-maven-plugin'),
      googleRepository
    }
  };
}

function parseDependency(dependency, resolve) {
  const exclusions = asArray(dependency.exclusions?.exclusion)
    .map((exclusion) => ({
      groupId: resolve(scalar(exclusion.groupId)),
      artifactId: resolve(scalar(exclusion.artifactId))
    }))
    .filter((exclusion) => exclusion.groupId || exclusion.artifactId);

  return {
    groupId: resolve(scalar(dependency.groupId)),
    artifactId: resolve(scalar(dependency.artifactId)),
    version: resolve(scalar(dependency.version)),
    scope: resolve(scalar(dependency.scope) || 'compile'),
    type: resolve(scalar(dependency.type) || 'jar'),
    classifier: resolve(scalar(dependency.classifier)),
    optional: scalar(dependency.optional) === 'true',
    exclusions
  };
}

function resolveProperty(value, properties) {
  if (typeof value !== 'string') {
    return value || '';
  }

  return value.replace(/\$\{([^}]+)\}/g, (_match, key) => {
    const resolved = properties[key];
    return resolved === undefined ? `\${${key}}` : resolveProperty(resolved, properties);
  });
}

function generateGradleArtifacts(model) {
  const { coordinates, properties, dependencies, managedDependencies, repositories, features } = model;
  const usesDependencyManagement = features.springBoot ||
    managedDependencies.some(
      (dependency) => dependency.type === 'pom' && dependency.scope === 'import'
    );
  const plugins = [
    "id 'java'",
    ...(features.springBoot ? [
      "id 'org.springframework.boot' version '3.3.5'"
    ] : []),
    ...(usesDependencyManagement ? [
      "id 'io.spring.dependency-management' version '1.1.6'"
    ] : []),
    ...(features.jacoco ? ["id 'jacoco'"] : []),
    ...(features.sonar ? ["id 'org.sonarqube' version '5.1.0.4882'"] : []),
    ...(features.googleRepository ? ["id 'maven-publish'"] : [])
  ];

  const repositoryLines = [
    'mavenCentral()',
    ...repositories.map((repository) =>
      repository.url.startsWith('artifactregistry://')
        ? `maven { url = uri('${escapeGroovy(repository.url)}') }`
        : `maven { url = uri('${escapeGroovy(repository.url)}') }`
    )
  ];

  const boms = managedDependencies
    .filter((dependency) => dependency.type === 'pom' && dependency.scope === 'import')
    .map((dependency) => `mavenBom '${coordinate(dependency)}'`);

  const dependencyLines = dependencies
    .filter((dependency) => !(dependency.type === 'pom' && dependency.scope === 'import'))
    .map(renderDependency);

  const buildGradle = `plugins {
${plugins.map((plugin) => `  ${plugin}`).join('\n')}
}

group = findProperty('group') ?: '${escapeGroovy(coordinates.groupId)}'
version = findProperty('version') ?: '${escapeGroovy(coordinates.version)}'
description = '${escapeGroovy(coordinates.description)}'

java {
  sourceCompatibility = JavaVersion.toVersion('${escapeGroovy(properties.javaVersion)}')
  targetCompatibility = JavaVersion.toVersion('${escapeGroovy(properties.javaVersion)}')
}

repositories {
${repositoryLines.map((line) => `  ${line}`).join('\n')}
}

${boms.length ? `dependencyManagement {
  imports {
${boms.map((bom) => `    ${bom}`).join('\n')}
  }
}
` : ''}dependencies {
${dependencyLines.map((line) => `  ${line}`).join('\n') || "  // No Maven dependencies detected."}
}

tasks.withType(JavaCompile).configureEach {
  options.encoding = '${escapeGroovy(properties.encoding || 'UTF-8')}'
  options.release = ${Number(properties.javaVersion) || 17}
}

tasks.withType(Test).configureEach {
  useJUnitPlatform()
  jvmArgs '--add-opens=java.base/java.lang=ALL-UNNAMED',
    '--add-opens=java.base/java.util=ALL-UNNAMED'
}

${features.failsafe ? `tasks.register('integrationTest', Test) {
  description = 'Runs integration tests migrated from Maven Failsafe.'
  group = 'verification'
  useJUnitPlatform()
  testClassesDirs = sourceSets.test.output.classesDirs
  classpath = sourceSets.test.runtimeClasspath
  include '**/*IT.class', '**/*ITCase.class'
}

tasks.named('check') {
  dependsOn tasks.named('integrationTest')
}
` : ''}${features.jacoco ? `jacocoTestReport {
  dependsOn test
  reports {
    xml.required = true
    html.required = true
  }
  afterEvaluate {
    classDirectories.setFrom(files(classDirectories.files.collect {
      fileTree(dir: it, exclude: [
        '**/model/**',
        '**/entity/**',
        '**/dto/**',
        '**/*Application.class'
      ])
    }))
  }
}
` : ''}${features.sonar ? "apply from: 'gradle/sonar.gradle'\n" : ''}${features.googleRepository ? "apply from: 'gradle/googleArtifactory.gradle'\n" : ''}`;

  const gradleProperties = `group=${coordinates.groupId}
version=${coordinates.version}
name=${coordinates.name}
projectKey=${coordinates.artifactId}
${features.googleRepository ? `googleRepositoryUrl=${features.googleRepository}\n` : ''}org.gradle.jvmargs=-Xmx2g -Dfile.encoding=UTF-8
org.gradle.daemon=true
systemProp.org.gradle.internal.http.connectionTimeout=60000
systemProp.org.gradle.internal.http.socketTimeout=60000
`;

  return {
    'build.gradle': `${buildGradle.trimEnd()}\n`,
    'gradle.properties': gradleProperties,
    'settings.gradle': `rootProject.name = '${escapeGroovy(coordinates.artifactId)}'\n`,
    ...(features.sonar ? { 'gradle/sonar.gradle': SONAR_TEMPLATE } : {}),
    ...(features.googleRepository
      ? { 'gradle/googleArtifactory.gradle': GOOGLE_ARTIFACTORY_TEMPLATE }
      : {})
  };
}

function renderDependency(dependency) {
  const configuration = mapScope(dependency);
  const dependencyNotation = coordinate(dependency);
  const exclusionBlock = dependency.exclusions.length
    ? ` {\n${dependency.exclusions.map((exclusion) =>
      `    exclude group: '${escapeGroovy(exclusion.groupId)}', module: '${escapeGroovy(exclusion.artifactId)}'`
    ).join('\n')}\n  }`
    : '';

  const primary = `${configuration} '${escapeGroovy(dependencyNotation)}'${exclusionBlock}`;
  if (dependency.scope === 'provided' && isLombok(dependency)) {
    return `${primary}\n  annotationProcessor '${escapeGroovy(dependencyNotation)}'`;
  }

  return primary;
}

function mapScope(dependency) {
  if (dependency.scope === 'test') {
    return 'testImplementation';
  }
  if (dependency.scope === 'runtime') {
    return 'runtimeOnly';
  }
  if (dependency.scope === 'provided' || dependency.optional) {
    return 'compileOnly';
  }
  return 'implementation';
}

function isLombok(dependency) {
  return dependency.groupId === 'org.projectlombok' ||
    dependency.artifactId.toLowerCase().includes('lombok');
}

function coordinate(dependency) {
  return [dependency.groupId, dependency.artifactId, dependency.version]
    .filter(Boolean)
    .join(':');
}

async function convertMavenToGradle(projectDirectory, {
  cutover = false,
  output = console.log,
  platform = process.platform,
  fileSystem = {
    access,
    chmod,
    copyFile,
    mkdir,
    readFile,
    readdir,
    rm,
    writeFile
  },
  execute = executeFile,
  wrapperJarSource = WRAPPER_JAR_SOURCE
} = {}) {
  const directory = path.resolve(projectDirectory || process.cwd());
  const pomPath = path.join(directory, 'pom.xml');
  const buildPath = path.join(directory, 'build.gradle');

  if (!(await exists(pomPath, fileSystem))) {
    throw new MavenToGradleError(`No se encontrรณ pom.xml en ${directory}.`);
  }
  if (await exists(buildPath, fileSystem)) {
    throw new MavenToGradleError(
      `Ya existe ${buildPath}; la conversiรณn no sobrescribe un build Gradle existente.`
    );
  }

  const model = parsePom(await fileSystem.readFile(pomPath, 'utf8'));
  const artifacts = generateGradleArtifacts(model);
  await writeArtifacts(directory, artifacts, fileSystem);
  await installGradleWrapper(directory, { platform, fileSystem, wrapperJarSource });

  const validation = await validateGradleBuild(directory, { platform, execute });
  if (cutover) {
    await applyCutover(directory, fileSystem);
  } else {
    output('Maven y Gradle convivirรกn temporalmente: pom.xml, .mvn/ y target/ se conservan.');
  }

  output('Conversiรณn Maven โ�� Gradle completada.');
  output(`Proyecto Gradle: ${path.join(directory, 'build.gradle')}`);
  output('La conversiรณn estรก lista para continuar con las siguientes estaciones de migraciรณn.');

  return {
    projectDirectory: directory,
    model,
    generatedFiles: Object.keys(artifacts).map((fileName) => path.join(directory, fileName)),
    wrapperFiles: [
      path.join(directory, 'gradlew'),
      path.join(directory, 'gradlew.bat'),
      path.join(directory, 'gradle', 'wrapper', 'gradle-wrapper.properties'),
      path.join(directory, 'gradle', 'wrapper', 'gradle-wrapper.jar')
    ],
    validation,
    cutover
  };
}

async function writeArtifacts(directory, artifacts, fileSystem) {
  await Promise.all(Object.entries(artifacts).map(async ([relativePath, content]) => {
    const filePath = path.join(directory, relativePath);
    await fileSystem.mkdir(path.dirname(filePath), { recursive: true });
    await fileSystem.writeFile(filePath, content, 'utf8');
  }));
  await updateGitignore(directory, fileSystem);
}

async function installGradleWrapper(directory, { platform, fileSystem, wrapperJarSource }) {
  if (!(await exists(wrapperJarSource, fileSystem))) {
    throw new MavenToGradleError(
      `No se encontrรณ el asset ${wrapperJarSource} para instalar Gradle Wrapper.`
    );
  }

  const wrapperDirectory = path.join(directory, 'gradle', 'wrapper');
  await fileSystem.mkdir(wrapperDirectory, { recursive: true });
  await Promise.all([
    fileSystem.writeFile(path.join(directory, 'gradlew'), GRADLEW_UNIX, 'utf8'),
    fileSystem.writeFile(path.join(directory, 'gradlew.bat'), GRADLEW_WINDOWS, 'utf8'),
    fileSystem.writeFile(
      path.join(wrapperDirectory, 'gradle-wrapper.properties'),
      `distributionBase=GRADLE_USER_HOME
distributionPath=wrapper/dists
distributionUrl=https\\://services.gradle.org/distributions/gradle-${GRADLE_VERSION}-bin.zip
networkTimeout=60000
validateDistributionUrl=true
zipStoreBase=GRADLE_USER_HOME
zipStorePath=wrapper/dists
`,
      'utf8'
    ),
    fileSystem.copyFile(
      wrapperJarSource,
      path.join(wrapperDirectory, 'gradle-wrapper.jar')
    )
  ]);

  if (platform !== 'win32') {
    await fileSystem.chmod(path.join(directory, 'gradlew'), 0o755);
  }
}

async function updateGitignore(directory, fileSystem) {
  const gitignorePath = path.join(directory, '.gitignore');
  const current = (await exists(gitignorePath, fileSystem))
    ? await fileSystem.readFile(gitignorePath, 'utf8')
    : '';
  const required = ['.gradle/', 'build/', '!gradle/wrapper/gradle-wrapper.jar'];
  const missing = required.filter((entry) =>
    !current.split(/\r?\n/).includes(entry)
  );

  if (missing.length) {
    const separator = current && !current.endsWith('\n') ? '\n' : '';
    await fileSystem.writeFile(
      gitignorePath,
      `${current}${separator}${missing.join('\n')}\n`,
      'utf8'
    );
  }
}

async function validateGradleBuild(directory, { platform, execute }) {
  const command = platform === 'win32' ? 'gradlew.bat' : './gradlew';
  const commandPath = platform === 'win32' ? path.join(directory, command) : command;

  try {
    const result = await execute(commandPath, ['compileJava'], {
      cwd: directory,
      windowsHide: true
    });
    return {
      command: `${command} compileJava`,
      stdout: result.stdout,
      stderr: result.stderr
    };
  } catch (cause) {
    throw new MavenToGradleError(
      'La estructura Gradle se generรณ, pero fallรณ la validaciรณn `compileJava`.',
      { cause, stdout: cause.stdout, stderr: cause.stderr }
    );
  }
}

async function applyCutover(directory, fileSystem) {
  await fileSystem.rm(path.join(directory, 'pom.xml'), { force: true });
  await fileSystem.rm(path.join(directory, '.mvn'), { recursive: true, force: true });
  await fileSystem.rm(path.join(directory, 'target'), { recursive: true, force: true });
}

async function exists(filePath, fileSystem) {
  try {
    await fileSystem.access(filePath, constants.F_OK);
    return true;
  } catch {
    return false;
  }
}

function asObject(value) {
  return value && typeof value === 'object' && !Array.isArray(value) ? value : {};
}

function asArray(value) {
  return Array.isArray(value) ? value : value ? [value] : [];
}

function scalar(value) {
  return typeof value === 'object' ? value?.['#text'] : value || '';
}

function escapeGroovy(value) {
  return String(value || '').replace(/\\/g, '\\\\').replace(/'/g, "\\'");
}

